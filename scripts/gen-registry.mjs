// Generates lib/generated/registry.ts with static imports for every test
// definition and lazy loaders for every message file, so that all content is
// bundled (no runtime filesystem access needed in route handlers).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const order = JSON.parse(fs.readFileSync(path.join(root, "content/tests.json"), "utf8"));
const localesSrc = fs.readFileSync(path.join(root, "lib/i18n/locales.ts"), "utf8");
const locales = [...localesSrc.match(/locales = \[([\s\S]*?)\]/)[1].matchAll(/"([a-z]+)"/g)].map((m) => m[1]);

const available = order.filter((slug) =>
  fs.existsSync(path.join(root, "content/definitions", `${slug}.json`)),
);
const missing = order.filter((slug) => !available.includes(slug));
if (missing.length) console.warn(`[registry] skipping tests without definition: ${missing.join(", ")}`);

const ident = (slug) => `def_${slug.replace(/-/g, "_")}`;
const lines = [
  "// AUTO-GENERATED by scripts/gen-registry.mjs. Do not edit by hand.",
  'import type { TestDefinition } from "@/lib/tests/types";',
  ...available.map((slug) => `import ${ident(slug)} from "@/content/definitions/${slug}.json";`),
  "",
  "export const definitions = [",
  ...available.map((slug) => `  ${ident(slug)},`),
  "] as unknown as TestDefinition[];",
  "",
  "export const messageLoaders: Record<string, () => Promise<unknown>> = {",
];
for (const locale of locales) {
  const files = ["ui", "email", ...available.map((slug) => `tests/${slug}`)];
  for (const file of files) {
    if (!fs.existsSync(path.join(root, "messages", locale, `${file}.json`))) continue;
    lines.push(`  "${locale}/${file}": () => import("@/messages/${locale}/${file}.json").then((m) => m.default),`);
  }
}
lines.push("};", "");

fs.mkdirSync(path.join(root, "lib/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "lib/generated/registry.ts"), lines.join("\n"));
console.log(`[registry] ${available.length} tests, ${lines.filter((l) => l.includes("import(")).length} message files`);
